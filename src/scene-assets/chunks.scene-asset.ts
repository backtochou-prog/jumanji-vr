/**
 * Vegetation, rocks and deadwood as STATIC-BATCHED culling cells.
 *
 * Why not GPU instancing? Measured with tools/asset-stats.mjs: instancing one
 * draw per species per cell either cannot cull (coarse cells: ~209k triangles
 * visible from the spawn) or explodes the draw count (fine cells: 274 draws).
 * Static batching merges everything of one material inside a 28 m cell into ONE
 * mesh: a handful of draws, exact frustum/distance culling per cell, and every
 * instance can carry its own scale, yaw, ground tilt and colour tint (so no two
 * plants look identical). Memory is the price (merged copies); it is small here.
 *
 * Data comes from src/world/baked.ts (generated by tools/generate-scene.mjs):
 *   instances[class][assetId] = flat [x, y, z, yaw, tiltX, tiltZ, scale, ...]
 * Prototypes are the same procedural species factories as before. Biology is
 * preserved: the scale in the data is uniform per instance; tint is +-9 %.
 */
import { BufferGeometry, Matrix4, Mesh, Quaternion, Vector3 } from '@iwsdk/core';
import { BAKED } from '../world/baked.js';
import { CHUNK, chunkIndex } from '../world/layout.js';
import type { ChunkClass } from '../world/layout.js';
import { makeRandom } from '../world/layout.js';
import type { RockKind } from './rocks.scene-asset.js';
import { createBranch, createLog, createRoots } from './deadwood.scene-asset.js';
import { mergeBaked } from './lib/geo.js';
import { barkMaterial, foliageCardMaterial, rockMaterial } from './lib/materials.js';
import {
  createBroadleaf,
  createFernCluster,
  createPads,
  createPalm,
  createPatch,
  createReed,
  createShrub,
  createTreeFern,
} from './plants.scene-asset.js';
import { createRock } from './rocks.scene-asset.js';
import { createTree } from './trees.scene-asset.js';
import type { TreeKind } from '../world/placements.js';

/** Build the prototype mesh for a baked asset id, e.g. `tree-tall-1`, `tree-giant-lo`, `fern-cluster-2`, `rock-boulder-0`. */
function prototype(id: string): Mesh {
  const [a, b, c] = id.split('-');
  if (a === 'tree') return createTree(b as TreeKind, c === 'lo' ? 0 : Number(c), c === 'lo' ? 'lo' : 'hi');
  if (a === 'fern') return createFernCluster(Number(c));
  if (a === 'treefern') return createTreeFern(Number(b));
  if (a === 'palm') return createPalm(Number(b));
  if (a === 'broadleaf') return createBroadleaf(Number(b));
  if (a === 'shrub') return createShrub(Number(b));
  if (a === 'patch') return createPatch(Number(b));
  if (a === 'reed') return createReed(Number(b));
  if (a === 'pads') return createPads(Number(b));
  if (a === 'rock') return createRock(b as RockKind, Number(c));
  if (a === 'log') return createLog(Number(b));
  if (a === 'branch') return createBranch(Number(b));
  if (a === 'roots') return createRoots(Number(b));
  throw new Error(`unknown vegetation prototype ${id}`);
}

const MATERIAL: Record<ChunkClass, typeof foliageCardMaterial | typeof rockMaterial | typeof barkMaterial> = {
  'trees-hi': foliageCardMaterial,
  'trees-lo': foliageCardMaterial,
  'trees-far': foliageCardMaterial,
  plants: foliageCardMaterial,
  ground: foliageCardMaterial,
  rocks: rockMaterial,
  deadwood: barkMaterial,
};

const protoCache = new Map<string, BufferGeometry>();
const protoGeo = (id: string): BufferGeometry => {
  let g = protoCache.get(id);
  if (!g) {
    g = prototype(id).geometry;
    protoCache.set(id, g);
  }
  return g;
};

const qx = new Quaternion();
const qz = new Quaternion();
const qy = new Quaternion();
const AX = new Vector3(1, 0, 0);
const AY = new Vector3(0, 1, 0);
const AZ = new Vector3(0, 0, 1);

/** Ids of every chunk asset: `veg-<class>-<ix>-<iz>`. Same list the scene generator wrote nodes for. */
export const CHUNK_ASSETS: { id: string; cls: ChunkClass; ix: number; iz: number }[] = (() => {
  const seen = new Map<string, { id: string; cls: ChunkClass; ix: number; iz: number }>();
  for (const cls of Object.keys(BAKED.instances) as ChunkClass[]) {
    for (const flat of Object.values(BAKED.instances[cls])) {
      for (let i = 0; i < flat.length; i += 7) {
        const [ix, iz] = chunkIndex(flat[i], flat[i + 2]);
        const id = `veg-${cls}-${ix}-${iz}`;
        if (!seen.has(id)) seen.set(id, { id, cls, ix, iz });
      }
    }
  }
  return [...seen.values()];
})();

/** Merge every instance of one class that falls in cell (ix, iz) into one mesh. */
export function createChunk(cls: ChunkClass, ix: number, iz: number): Mesh {
  const rng = makeRandom(ix * 7919 + iz * 104729 + cls.length * 31);
  const items: { geo: BufferGeometry; m: Matrix4; tint: [number, number, number] }[] = [];
  for (const [id, flat] of Object.entries(BAKED.instances[cls])) {
    for (let i = 0; i < flat.length; i += 7) {
      if (chunkIndex(flat[i], flat[i + 2]).join() !== `${ix},${iz}`) continue;
      const [x, y, z, yaw, tx, tz, s] = flat.slice(i, i + 7);
      // World-frame ground tilt composed with the instance's own yaw.
      qx.setFromAxisAngle(AX, tx);
      qz.setFromAxisAngle(AZ, tz);
      qy.setFromAxisAngle(AY, yaw);
      const q = new Quaternion().multiplyQuaternions(qz, qx).multiply(qy);
      const k = 0.91 + 0.18 * rng();
      items.push({ geo: protoGeo(id), m: new Matrix4().compose(new Vector3(x, y, z), q, new Vector3(s, s, s)), tint: [k, k * (0.97 + 0.06 * rng()), k * (0.95 + 0.1 * rng())] });
    }
  }
  const mesh = new Mesh(mergeBaked(items), MATERIAL[cls]);
  mesh.name = `Chunk_${cls}_${ix}_${iz}`;
  return mesh;
}

export { CHUNK };
