/**
 * Vegetation, rocks and deadwood as STATIC-BATCHED culling cells.
 *
 * Why not GPU instancing? Measured with tools/asset-stats.mjs: instancing one
 * draw per species per cell either cannot cull (coarse cells: ~209k triangles
 * visible from the spawn) or explodes the draw count (fine cells: 274 draws).
 * Static batching merges everything of one material inside a 28 m cell into ONE
 * mesh: a handful of draws, exact frustum/distance culling per cell, and every
 * instance can carry its own scale, yaw, ground tilt and colour tint (so no two
 * plants look identical). Memory is the price (merged copies); it is small here.
 *
 * Data comes from src/world/baked.ts (generated by tools/generate-scene.mjs):
 *   instances[class][assetId] = flat [x, y, z, yaw, tiltX, tiltZ, scale, ...]
 * Prototypes are the same procedural species factories as before. Biology is
 * preserved: the scale in the data is uniform per instance; tint is +-9 % in value, and trees and crowns also follow a world-space colour field
 * (see `colourField`) that is a pure function of the instance's world position.
 */
