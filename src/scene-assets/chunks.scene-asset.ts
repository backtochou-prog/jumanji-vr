/** Build the prototype mesh for a baked asset id, e.g. `tree-tall-1`, `tree-giant-lo`, `fern-cluster-2`, `rock-boulder-0`. */
function prototype(id: string): Mesh {
  const [a, b, c] = id.split('-');
  if (a === 'tree') return createTree(b as TreeKind, c === 'lo' ? 0 : Number(c), c === 'lo' ? 'lo' : 'hi');
  if (a === 'fern') return createFernCluster(Number(c));
  if (a === 'treefern') return createTreeFern(Number(b));
  if (a === 'palm') return createPalm(Number(b));
  if (a === 'broadleaf') return createBroadleaf(Number(b));
  if (a === 'shrub') return createShrub(Number(b));
  if (a === 'patch') return createPatch(Number(b));
  if (a === 'meadow') return b === 'tuft' ? createMeadowTuft(Number(c)) : createMeadowFlowers(Number(c));
  if (a === 'reed') return createReed(Number(b));
  if (a === 'pads') return createPads(Number(b));
  if (a === 'rock') return createRock(b as RockKind, Number(c));
  if (a === 'canopy') return createCanopyClump(Number(b));
  if (a === 'pinnacle') return createPinnacle(Number(b));
  if (a === 'vine') return createVineCurtain(Number(b));
  if (a === 'log') return createLog(Number(b));
  if (a === 'branch') return createBranch(Number(b));
  if (a === 'roots') return createRoots(Number(b));
  throw new Error(`unknown vegetation prototype ${id}`);
}

const MATERIAL: Record<ChunkClass, typeof foliageCardMaterial | typeof rockMaterial | typeof barkMaterial | typeof canopyMaterial> = {
  'trees-hi': foliageCardMaterial,
  'trees-lo': foliageCardMaterial,
  'trees-far': foliageCardMaterial,
  plants: plantFoliageMaterial,
  ground: plantFoliageMaterial,
  rocks: rockMaterial,
  deadwood: barkMaterial,
  canopy: canopyMaterial,
  crags: rockMaterial,
};

const protoCache = new Map<string, BufferGeometry>();
const protoGeo = (id: string): BufferGeometry => {
  let g = protoCache.get(id);
  if (!g) {
    g = prototype(id).geometry;
    protoCache.set(id, g);
  }
  return g;
};

const qx = new Quaternion();
const qz = new Quaternion();
const qy = new Quaternion();
const AX = new Vector3(1, 0, 0);
const AY = new Vector3(0, 1, 0);
const AZ = new Vector3(0, 0, 1);

/** Ids of every chunk asset: `veg-<class>-<ix>-<iz>`. Same list the scene generator wrote nodes for. */
export const CHUNK_ASSETS: { id: string; cls: ChunkClass; ix: number; iz: number }[] = (() => {
  const seen = new Map<string, { id: string; cls: ChunkClass; ix: number; iz: number }>();
  for (const cls of Object.keys(BAKED.instances) as ChunkClass[]) {
    for (const flat of Object.values(BAKED.instances[cls])) {
      for (let i = 0; i < flat.length; i += 7) {
        const [ix, iz] = chunkIndex(flat[i], flat[i + 2], CELL_SIZE[cls]);
        const id = `veg-${cls}-${ix}-${iz}`;
        if (!seen.has(id)) seen.set(id, { id, cls, ix, iz });
      }
    }
  }
  return [...seen.values()];
})();

type RGB = [number, number, number];

/** Integer hash of a world position (cm) and a salt -> [0,1). Position only, never the sequential rng: the detailed, cheap and far versions of a tree agree. */
function posHash(x: number, z: number, salt: number): number {
  let h = (Math.round(x * 100) * 374761393 + Math.round(z * 100) * 668265263 + salt * 2147483647) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}

/**
 * World-space colour field for crowns, as colour multipliers: LEAF vertices get the hue (yellow-green and blue-green drifts of +-12..18 % across
 * ~60 m patches from fbm(x, z), and rarely a muted copper flush on a giant or tall, a dry gold on any tree); WOOD vertices only the value jitter,
 * so trunks and limbs never turn green or copper. `kind` is the tree family ('canopy' for the valley's crown carpet: hue field only).
 */
function colourField(kind: string, x: number, z: number): { leaf: RGB; wood: RGB } {
  const k = 0.91 + 0.18 * posHash(x, z, 1);
  const kg = k * (0.97 + 0.06 * posHash(x, z, 2));
  const kb = k * (0.95 + 0.1 * posHash(x, z, 3));
  const c = Math.min(1, Math.max(-1, (fbm(x * 0.018, z * 0.018, 4711, 3) - 0.44) * 4.2));
  const hue: RGB = c >= 0 ? [1 + 0.17 * c, 1 + 0.04 * c, 1 - 0.18 * c] : [1 + 0.12 * c, 1, 1 - 0.12 * c];
  let accent: readonly [number, number, number] | null = null;
  let strength = 0;
  if (kind !== 'canopy') {
    if ((kind === 'giant' || kind === 'tall') && posHash(x, z, 7) < 1 / 14) {
      accent = FLUSH_TINT;
      strength = 0.6 + 0.4 * posHash(x, z, 8);
    } else if (posHash(x, z, 9) < 1 / 30) {
      accent = GOLD_TINT;
      strength = 0.6 + 0.4 * posHash(x, z, 10);
    }
  }
  const a: RGB = accent ? [1 + (accent[0] - 1) * strength, 1 + (accent[1] - 1) * strength, 1 + (accent[2] - 1) * strength] : [1, 1, 1];
  return { leaf: [k * hue[0] * a[0], kg * hue[1] * a[1], kb * hue[2] * a[2]], wood: [k, kg, kb] };
}

/** Merge every instance of one class that falls in cell (ix, iz) into one mesh. */
export function createChunk(cls: ChunkClass, ix: number, iz: number): Mesh {
  const rng = makeRandom(ix * 7919 + iz * 104729 + cls.length * 31);
  const items: { geo: BufferGeometry; m: Matrix4; tint: RGB; woodTint?: RGB }[] = [];
  const field = cls === 'trees-hi' || cls === 'trees-lo' || cls === 'trees-far' || cls === 'canopy';
  for (const [id, flat] of Object.entries(BAKED.instances[cls])) {
    for (let i = 0; i < flat.length; i += 7) {
      if (chunkIndex(flat[i], flat[i + 2], CELL_SIZE[cls]).join() !== `${ix},${iz}`) continue;
      const [x, y, z, yaw, tx, tz, s] = flat.slice(i, i + 7);
      // World-frame ground tilt composed with the instance's own yaw.
      qx.setFromAxisAngle(AX, tx);
      qz.setFromAxisAngle(AZ, tz);
      qy.setFromAxisAngle(AY, yaw);
      const q = new Quaternion().multiplyQuaternions(qz, qx).multiply(qy);
      const m = new Matrix4().compose(new Vector3(x, y, z), q, new Vector3(s, s, s));
      if (field) {
        const f = colourField(cls === 'canopy' ? 'canopy' : id.split('-')[1], x, z);
        items.push({ geo: protoGeo(id), m, tint: f.leaf, woodTint: cls === 'canopy' ? undefined : f.wood });
        continue;
      }
      const k = 0.91 + 0.18 * rng();
      items.push({ geo: protoGeo(id), m, tint: [k, k * (0.97 + 0.06 * rng()), k * (0.95 + 0.1 * rng())] });
    }
  }
  // aWind (tree wind weights) is only read by foliageCardMaterial: the tree classes keep it, everything else drops it
  const mesh = new Mesh(mergeBaked(items, cls === 'plants' || cls === 'ground', cls === 'trees-hi' || cls === 'trees-lo' || cls === 'trees-far'), MATERIAL[cls]);
  mesh.name = `Chunk_${cls}_${ix}_${iz}`;
  return mesh;
}

